test('root meanings retain the distinctions agreed in the pilot', () => {
  const root = word => corpus.roots.entries.find(entry => entry.wc === word);
  assert.match(root('character').zh, /字/);
  assert.match(root('word').zh, /词/);
  assert.equal(root('read').zh, '阅读');
  assert.equal(root('see').zh, '看见');
  assert.equal(root('want').zh, '想要');
  assert.equal(root('think').zh, '思考');
  for (const entry of corpus.roots.entries) {
    assert.equal(entry.pronunciation_policy, 'original English');
    assert.ok(entry.reading_status);
  }
});

test('duplicate root IDs and case-insensitive base words are detected', () => {
  const changed = copy();
  changed.roots.entries[1].id = changed.roots.entries[0].id;
  changed.roots.entries[1].wc = 'i';
  assert.throws(() => validateCorpus(changed), error => {
    assert.match(error.message, /duplicate id/);
    assert.match(error.message, /duplicate base word/);
    assert.match(error.message, /use I or lowercase/);
    return true;
  });
});

test('compound components must be known roots and concatenate exactly', () => {
  const unknown = copy();
  unknown.compounds.entries[0].components[0] = 'missing';
  assert.throws(() => validateCorpus(unknown), /unknown root missing/);
  const misspelled = copy();
  misspelled.compounds.entries[0].wc = 'oldpeople';
  assert.throws(() => validateCorpus(misspelled), /components do not concatenate/);
});

test('sentence IDs and vocabulary must be closed over the pilot data', () => {
  const changed = copy();
  changed.sentences.entries[0].id = '002';
  changed.sentences.entries[0].wc = 'I mysteryword.';
  assert.throws(() => validateCorpus(changed), error => {
    assert.match(error.message, /duplicate id/);
    assert.match(error.message, /expected consecutive id 001/);
    assert.match(error.message, /unknown token mysteryword/);
    return true;
  });
});

test('numbers must be complete, ordered, and generated by numberWord', () => {
  const missing = copy();
  missing.numbers.entries.pop();
  assert.throws(() => validateCorpus(missing), /expected 100 entries/);
  const reordered = copy();
  [reordered.numbers.entries[11], reordered.numbers.entries[12]] = [reordered.numbers.entries[12], reordered.numbers.entries[11]];
  assert.throws(() => validateCorpus(reordered), /complete and ordered/);
  const misspelled = copy();
  misspelled.numbers.entries[12].wc = 'twelve';
  assert.throws(() => validateCorpus(misspelled), /spelling differs from numberWord/);
});

test('sentence 040 does not add unsupported completion meaning', () => {
  const changed = copy();
  changed.sentences.entries[39].zh = '你看见书了吗？';
  assert.throws(() => validateCorpus(changed), /without added completion meaning/);
});

test('the public pilot contains original examples, not the novel sample', () => {
  for (const doc of Object.values(corpus)) assert.equal(doc.source, 'original project examples');
  const changed = copy();
  changed.sentences.entries[0].zh = '放开那个女巫';
  assert.throws(() => validateCorpus(changed), /external novel marker/);
  const source = copy();
  source.sentences.source = 'novel translation';
  assert.throws(() => validateCorpus(source), /source must be original project examples/);
});

test('malformed documents fail with validation diagnostics', () => {
  assert.throws(() => validateCorpus({}), error => {
    assert.equal(error.name, 'CorpusValidationError');
    assert.ok(error.problems.length > 0);
    return true;
  });
});
